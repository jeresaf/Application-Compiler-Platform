SCHEMA='acp-verification-result/1'
RESULTS={'PASS','FAIL','BLOCKED','NOT_RUN'}

def load_model(path,pin):
 raw=Path(path).read_bytes();require(sha(raw)==pin,'SOURCE_MODEL_FILE_DIGEST');return validate(json.loads(raw))

def seal(value):
 # Returned observation documents must not alias the host's input bindings.
 detached=json.loads(encode(value));return {**detached,'digest':digest(detached)}
def validate_result(value):
 require(set(value)=={'schema','scope','inputs','results','summary','releaseDisposition','digest'},'RESULT_FIELDS')
 require(value['schema']==SCHEMA and value['scope']=='QUALIFICATION_ONLY','RESULT_SCOPE')
 require(value['digest']==digest({k:v for k,v in value.items() if k!='digest'}),'RESULT_DIGEST')
 ids=[r['id'] for r in value['results']];require(len(ids)==len(set(ids)),'DUPLICATE_RESULT')
 require(all(r['result'] in RESULTS for r in value['results']),'RESULT_VOCABULARY')
 require(value['summary']==summary(value['results']),'RESULT_SUMMARY')
 require(value['releaseDisposition']=='PHASE6_RELEASE_CLOSURE_BLOCKED','RELEASE_BOUNDARY')
 return value

def summary(rows):return {s:sum(r['result']==s for r in rows) for s in sorted(RESULTS)}

def outcome(call):
 try:return 'PASS',call(),[]
 except (ValueError,OSError,KeyError,TypeError) as e:return 'FAIL',None,[type(e).__name__+':'+str(e).split('\n',1)[0][:180]]

class Session:
 """Host resolves exact approved compilation once, then uses real retained checks."""
 def __init__(self,root,baseline,baseline_sha256,source_model,source_model_sha256):
  self.root=Path(root).absolute();self.baseline=Path(baseline);self.baseline_pin=baseline_sha256
  self.b,self.revisions=binding(baseline,baseline_sha256);self.model_path=Path(source_model);self.model_pin=source_model_sha256;self.model=load_model(source_model,source_model_sha256)
  # Reconstruct the exact original publication ancestry. A regeneration against
  # post-publication inventory has different CAS expected digests and is not the
  # original ArtifactPlan even when generated bytes are identical.
  self.candidate,self.snapshot,self.request,initial=inputs(self.b['domain'])
  with tempfile.TemporaryDirectory(prefix='acp-phase8-plan-') as temporary:
   store=FilesystemArtifactStore(Path(temporary)/self.b['domain']);store.apply(initial)
   store.adopt_human('frontend/src/extensions/identity.ts')
   self.plan=self.candidate.plan(self.snapshot,self.request,inventory=store.inventory())
  self.target=self.candidate.targets[(self.request.snapshot_digest,self.request.compiler,self.request.pipeline)]
  require(fingerprint(self.plan)==self.b['artifactPlanDigest'],'ARTIFACT_PLAN_BINDING')
  require(self.candidate.executions==self.b['compilerExecutions'],'COMPILATION_AUDIT_BINDING')
  require(self.target.obligations==self.plan.obligations,'TARGET_OBLIGATION_BINDING')
  require(self.model['bindingDigest']==self.baseline_pin and all(self.model['identity'][k]==self.b[k] for k in ('domain','canonicalDigest','generator','compiler','pipeline','artifactPlanDigest')),'SOURCE_MODEL_IDENTITY')
  self.inputs={'domain':self.b['domain'],'canonicalDigest':self.b['canonicalDigest'],'compiler':self.b['compiler'],'pipeline':self.b['pipeline'],'generator':self.b['generator'],'generatorBundle':self.candidate.bundle,'artifactPlanDigest':fingerprint(self.plan),'compilationAuditDigest':digest(self.candidate.executions),'targetIRDigest':fingerprint(self.target),'baselineSHA256':baseline_sha256,'sourceModelDigest':self.model['digest'],'sourceModelFileSHA256':source_model_sha256,'executorSHA256':sha(Path(__file__).read_bytes()),'sourceValidatorSHA256':sha((ROOT/'engineering/source_intelligence/model.py').read_bytes()),'provenanceVerifierSHA256':sha((ROOT/'engineering/generator_candidates/spring_vue_postgres_0_6/provenance.py').read_bytes())}
  self.input_digests=tuple('sha256:'+digest({k:self.inputs[k]}) for k in sorted(self.inputs))
  self.obligations={o.id:o for o in self.plan.obligations}
 def check_fresh(self):
  require(sha(self.baseline.read_bytes())==self.baseline_pin,'STALE_BASELINE')
  require(sha(self.model_path.read_bytes())==self.model_pin,'STALE_SOURCE_MODEL_FILE')
  require(sha(Path(__file__).read_bytes())==self.inputs['executorSHA256'],'STALE_EXECUTOR')
  current(self.model,self.root)
 def evaluate(self,execute=True,execution=None):
  require(type(execute) is bool,'EXECUTION_FLAG')
  rows=[]
  def add(id,kind,result,*,origins=(),artifacts=(),reason=(),obligation=None,observation=None):
   rows.append({'id':id,'kind':kind,'result':result,'origins':list(origins),'artifacts':list(artifacts),'obligation':obligation,'reasons':list(reason),'observation':observation})
  state,_,reason=outcome(self.check_fresh)
  fresh=state=='PASS'
  add('source-model-binding','SOURCE_BINDING','PASS' if fresh else 'BLOCKED',reason=reason,observation={'modelDigest':self.model['digest'],'completeness':self.model['completeness']})
  add('source-model-completeness','SOURCE_COMPLETENESS','PASS' if fresh and self.model['completeness']['fullyResolved'] else 'BLOCKED',reason=[] if fresh and self.model['completeness']['fullyResolved'] else ['PARTIAL_OR_STALE_SOURCE_ANALYSIS'])
  if execute:
   integrity,observed,errors=outcome(lambda:self.candidate.verify_materialized(self.root,self.plan,self.snapshot,self.request))
  else:integrity,observed,errors='NOT_RUN',None,['EXECUTOR_NOT_RUN']
  for artifact in self.plan.artifacts:
   f=self.b['files'][artifact.path]
   refs=[{'symbol':m['symbol'],'semantic':m['semantic'],'relationship':m['relationship']} for m in self.model['semanticMappings'] if m['literalLocation']['file']==artifact.path]
   for requirement in artifact.verification:
    # The generator currently declares only this exact offline predicate.
    supported=requirement=='target-source-integrity'
    add('artifact:'+artifact.path+':'+requirement,'ARTIFACT_VERIFICATION',integrity if supported else 'BLOCKED',origins=wire(artifact.mappings),artifacts=[{'path':artifact.path,'sha256':f['sha256'],'ownership':f['owner'],'sourceMappings':refs,'locationConfidence':f['historicalConfidence']}],reason=errors if supported else ['NO_EXECUTOR_FOR_DECLARED_REQUIREMENT'],observation={'executor':'SuccessorCandidate.verify_materialized','evaluationUnit':'ARTIFACT_PLAN_BUNDLE','requirement':requirement,'result':observed})
  for obligation in self.plan.obligations:
   origins=wire(obligation.origins);applicable=[a.path for a in self.plan.artifacts if set(obligation.origins)&set(a.mappings)]
   add('semantic:'+obligation.id,'SEMANTIC_OBLIGATION','NOT_RUN' if fresh and integrity=='PASS' and applicable else 'BLOCKED',origins=origins,artifacts=applicable,obligation=wire(obligation),reason=['NO_BEHAVIOR_RESULT_BOUND'] if applicable and fresh and integrity=='PASS' else ['INPUTS_NOT_VERIFIED_OR_ARTIFACT_MAPPING_MISSING'])
  deployment=json.loads(next(a.content.read()['text'] for a in self.plan.artifacts if a.path=='acp/deployment-requirements.json'))
  for section in ('requirements','taskInterfaceObligations'):
   for requirement in deployment.get(section,[]):
    origins=requirement.get('origins',[requirement['origin']] if 'origin' in requirement else [])
    require(origins and all(self.revisions.get(o['id'])==o['revision'] for o in origins),'DEPLOYMENT_ORIGIN_BINDING')
    add('deployment:'+digest([section,requirement]),'DEPLOYMENT_OBLIGATION','BLOCKED',origins=origins,artifacts=['acp/deployment-requirements.json'],reason=['INDEPENDENT_OPERATIONAL_OR_HUMAN_EVIDENCE_REQUIRED'],observation=requirement)
  result_inputs=self.inputs
  if execution is not None:
   rows=execution.apply(self,rows);result_inputs={**self.inputs,**execution.context}
  # An input can become stale during a verifier call. No affected PASS survives.
  after,_,after_errors=outcome(self.check_fresh)
  if after!='PASS':
   for row in rows:
    if row['result']=='PASS':row['result']='BLOCKED';row['reasons']=['INPUTS_CHANGED_OR_STALE',*after_errors]
  return validate_result(seal({'schema':SCHEMA,'scope':'QUALIFICATION_ONLY','inputs':result_inputs,'results':sorted(rows,key=lambda r:r['id']),'summary':summary(rows),'releaseDisposition':'PHASE6_RELEASE_CLOSURE_BLOCKED'}))
 def verify_retained(self,result,execution=None):
  """Compare a retained local result with independently rerun existing predicates.

  A checksum or caller-provided PASS label alone never establishes execution.
  This is local engineering replay, not an authenticated release attestation.
  """
  validate_result(result);require(result['inputs']=={**self.inputs,**(execution.context if execution is not None else {})},'STALE_OR_MISMATCHED_EVIDENCE');self.check_fresh()
  actual=self.evaluate(execution=execution);require(result==actual,'MISSING_OR_CHANGED_VERIFICATION_RESULT');return actual

@dataclass(frozen=True)
class ExistingEvidenceExecutor:
 """Existing logical EvidenceExecutor port, no arbitrary commands or release grant."""
 session: Session
 output: Path
 execution: object = None
 @property
 def inputs(self):return {**self.session.inputs,**(self.execution.context if self.execution is not None else {})}
 @property
 def input_digests(self):return tuple('sha256:'+digest({k:self.inputs[k]}) for k in sorted(self.inputs))
 def execute(self,plan,input_digests):
  request=plan.read();require(set(request)=={'schema','operation','inputsDigest'} and request['schema']=='acp-verification-request/1' and request['operation']=='VERIFY' and request['inputsDigest']==digest(self.inputs),'EXECUTION_REQUEST')
  require(tuple(input_digests)==self.input_digests,'EXECUTION_INPUT_DIGESTS')
  require(not self.output.resolve().is_relative_to(self.session.root.resolve()),'OUTPUT_INSIDE_APPLICATION')
  result=self.session.evaluate(execution=self.execution);raw=encode(result)
  with self.output.open('xb') as stream:stream.write(raw)
  return Document.of({'schema':'acp-verification-descriptor/1','scope':'QUALIFICATION_ONLY','resultDigest':result['digest'],'fileSHA256':sha(raw),'summary':result['summary'],'releaseDisposition':result['releaseDisposition']})
