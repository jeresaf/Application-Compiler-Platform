"""Run the successor coordination component against an owned PostgreSQL container."""
import argparse
import os
from pathlib import Path
import subprocess
import sys
from tempfile import TemporaryDirectory

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from engineering.generator_builds.runtime import database
from engineering.recovery.qualify import authenticated_database_ready


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--classpath-file', required=True, type=Path,
                        help='Use the classpath generated by the verified offline recovery build')
    args = parser.parse_args()
    classpath = args.classpath_file.read_text().strip()
    with TemporaryDirectory(prefix='acp-cardinality-') as directory:
        subprocess.run(['javac', '-cp', classpath, '-d', directory,
                        str(ROOT / 'engineering/cardinality/templates/TenantCoordination.java'),
                        str(ROOT / 'verification/cardinality/TenantCoordinationTest.java')],
                       check=True, timeout=60)
        with database() as container:
            authenticated_database_ready(container, os.environ['ACP_TEST_DATABASE_PASSWORD'])
            subprocess.run(['java', '-cp', directory + os.pathsep + classpath,
                            'acp.infrastructure.TenantCoordinationTest'], check=True, timeout=45)


if __name__ == '__main__':
    main()
